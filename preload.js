const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('orbit', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (cfg) => ipcRenderer.invoke('config:set', cfg),
  moveBy: (dx, dy) => ipcRenderer.send('win:move', dx, dy),
  showMenu: () => ipcRenderer.send('menu:show'),
  openSettings: () => ipcRenderer.send('settings:open'),
  closeSettings: () => ipcRenderer.send('settings:close'),
  runAction: (name, args) => ipcRenderer.invoke('action:run', name, args),
  browserRun: (name, args) => ipcRenderer.invoke('browser:run', name, args),
  voiceStatus: () => ipcRenderer.invoke('voice:status'),
  voiceDownload: () => ipcRenderer.invoke('voice:download'),
  onVoiceProgress: (cb) => ipcRenderer.on('voice:progress', (_e, p) => cb(p)),
  speak: (text) => ipcRenderer.invoke('voice:speak', text),
  wakeStatus: () => ipcRenderer.invoke('wake:status'),
  wakeDownload: () => ipcRenderer.invoke('wake:download'),
  onWakeProgress: (cb) => ipcRenderer.on('wake:progress', (_e, p) => cb(p)),
  wakeHear: (pcm) => ipcRenderer.invoke('wake:hear', pcm),
  showBubble: (b) => ipcRenderer.send('bubble:show', b),
  onAmbush: (cb) => ipcRenderer.on('ambush', (_e, b) => cb(b)),
  typeText: (text) => ipcRenderer.invoke('type:text', text),
  hideBubble: () => ipcRenderer.send('bubble:hide'),
  onBubble: (cb) => ipcRenderer.on('bubble', (_e, b) => cb(b)),
  appsInfo: () => ipcRenderer.invoke('apps:info'),
  rescanApps: () => ipcRenderer.invoke('apps:rescan'),
  stunt: (name) => ipcRenderer.send('orb:stunt', name),
  transform: (form) => ipcRenderer.send('orb:transform', form),
  setDefence: (on) => ipcRenderer.send('orb:defence', on),
  setSkin: (name) => ipcRenderer.send('orb:setSkin', name),
  onSkin: (cb) => ipcRenderer.on('orb:skin', (_e, name) => cb(name)),
  setCharacter: (name) => ipcRenderer.send('orb:setCharacter', name),
  onCharacter: (cb) => ipcRenderer.on('orb:character', (_e, name) => cb(name)),
  onClaudeEvent: (cb) => ipcRenderer.on('claude:event', (_e, r) => cb(r)),
  claudeStatus: () => ipcRenderer.invoke('claude:status'),
  agentsInfo: () => ipcRenderer.invoke('agents:info'),
  claudeDecide: (id, behavior, extra) => ipcRenderer.send('claude:decide', id, behavior, extra),
  bubbleHover: (on) => ipcRenderer.send('bubble:hover', on),
  openChat: (session) => ipcRenderer.send('chat:open', session),
  closeChat: () => ipcRenderer.send('chat:close'),
  onChat: (cb) => ipcRenderer.on('chat', (_e, d) => cb(d)),
  chatSend: (session, text) => ipcRenderer.invoke('chat:send', session, text),
  logChat: (role, text) => ipcRenderer.send('log:append', role, text),
  reportState: (state) => ipcRenderer.send('orb:state', state),
  interact: () => ipcRenderer.send('orb:interact'),
  setDragging: (on) => ipcRenderer.send('orb:drag', on),
  onMotion: (cb) => ipcRenderer.on('motion', (_e, m) => cb(m)),
  onToggle: (cb) => ipcRenderer.on('orb:toggle', () => cb()),
  onConfigChanged: (cb) => ipcRenderer.on('config:changed', () => cb()),

  // Nyx capabilities
  nyx: {
    focusedWindow: () => ipcRenderer.invoke('nyx:focusedWindow'),
    listWindows: () => ipcRenderer.invoke('nyx:listWindows'),
    screenshot: (windowId) => ipcRenderer.invoke('nyx:screenshot', { windowId }),
    clipboard: {
      read: (format) => ipcRenderer.invoke('nyx:clipboard:read', format),
      write: (data) => ipcRenderer.invoke('nyx:clipboard:write', data),
    },
    system: {
      vitals: () => ipcRenderer.invoke('nyx:system:vitals'),
    },
    focusWindow: (windowId) => ipcRenderer.invoke('nyx:focusWindow', windowId),
  },

  // Chat via Hermes bridge
  chat: (text, sessionId) => ipcRenderer.send('chat', { text, sessionId }),
  onHermesReply: (cb) => ipcRenderer.on('hermes:reply', (_e, msg) => cb(msg)),
});
